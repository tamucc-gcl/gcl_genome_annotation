#!/usr/bin/env python3
"""
generate_annotation_report.py
=============================
Assemble a Markdown annotation report with embedded PNG plot references.

Parses upstream module outputs, computes summary statistics, and writes
a GitHub-viewable Markdown report with relative image paths to the
plots directory generated by annotation_report_plots.R.

Usage:
    python3 generate_annotation_report.py \
        --assembly_id ID \
        --assembly_stats assembly_stats.tsv \
        --gff3 annotated.gff3 \
        --gene_summary gene_product_summary.tsv \
        --functional_tsv functional_annotations.tsv \
        --repeat_tbl repeat.tbl \
        --repeat_tbl_full buildSummary.tbl \
        --busco_txt busco.txt \
        --omark_summary omark.summary.txt \
        --omark_detailed omark_detailed.txt \
        --agat_stats agat_stats \
        --trnascan_tsv trnascan.tsv \
        --infernal_tblout infernal.tblout \
        --telomere_gff3 telomeres.gff3 \
        --centromere_gff3 centromere.gff3 \
        --plots_dir plots/ \
        --outfile report.md
"""

import argparse
import csv
import os
import re
import sys
from collections import Counter, defaultdict, OrderedDict
from datetime import datetime


# ═════════════════════════════════════════════════════════════════════════════
# Helpers
# ═════════════════════════════════════════════════════════════════════════════

def parse_gff3_features(path):
    """Parse GFF3 into list of dicts. Skip comments and blank lines."""
    features = []
    with open(path) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            cols = line.rstrip("\n").split("\t")
            if len(cols) != 9:
                continue
            attrs = OrderedDict()
            for token in cols[8].split(";"):
                token = token.strip()
                if "=" in token:
                    k, v = token.split("=", 1)
                    attrs[k] = v
            features.append({
                "seqid": cols[0], "source": cols[1], "type": cols[2],
                "start": int(cols[3]), "end": int(cols[4]),
                "score": cols[5], "strand": cols[6], "phase": cols[7],
                "attributes": attrs, "length": int(cols[4]) - int(cols[3]) + 1,
            })
    return features


def fmt(n):
    """Format integer with commas."""
    return f"{n:,}"


def pct(n, total):
    """Percentage string."""
    if total == 0:
        return "0.0%"
    return f"{100 * n / total:.1f}%"


def img(plots_dir, filename):
    """Return markdown image reference if file exists."""
    path = os.path.join(plots_dir, filename)
    if os.path.exists(path):
        return f"![{filename}]({plots_dir}/{filename})\n"
    return ""


def read_file_text(path):
    """Read file as text, return empty string if missing."""
    try:
        with open(path) as f:
            return f.read()
    except (FileNotFoundError, IOError):
        return ""


# ═════════════════════════════════════════════════════════════════════════════
# Main
# ═════════════════════════════════════════════════════════════════════════════

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--assembly_id", required=True)
    parser.add_argument("--assembly_stats", required=True)
    parser.add_argument("--gff3", required=True)
    parser.add_argument("--gene_summary", required=True)
    parser.add_argument("--functional_tsv", required=True)
    parser.add_argument("--repeat_tbl", required=True)
    parser.add_argument("--repeat_tbl_full", required=True)
    parser.add_argument("--busco_txt", required=True)
    parser.add_argument("--omark_summary", required=True)
    parser.add_argument("--omark_detailed", required=True)
    parser.add_argument("--agat_stats", required=True)
    parser.add_argument("--trnascan_tsv", required=True)
    parser.add_argument("--infernal_tblout", required=True)
    parser.add_argument("--telomere_gff3", required=True)
    parser.add_argument("--centromere_gff3", required=True)
    parser.add_argument("--plots_dir", required=True)
    parser.add_argument("--outfile", required=True)
    args = parser.parse_args()

    asm = args.assembly_id
    pd = args.plots_dir

    # ── Parse inputs ──────────────────────────────────────────────────────
    gff = parse_gff3_features(args.gff3)
    braker  = [f for f in gff if f["source"] == "BRAKER3"]
    trna_f  = [f for f in gff if f["source"] == "tRNAscan-SE"]
    ncrna_f = [f for f in gff if f["source"] == "Infernal"]
    repeat_f = [f for f in gff if f["source"] == "RepeatMasker"]
    telo_f  = [f for f in gff if f["source"] == "tidk"]
    centro_f = [f for f in gff if f["source"] == "centroAnno"]

    genes = [f for f in braker if f["type"] == "gene"]
    mrnas = [f for f in braker if f["type"] in ("mRNA", "transcript")]
    exons = [f for f in braker if f["type"] == "exon"]
    cdss  = [f for f in braker if f["type"] == "CDS"]
    introns = [f for f in braker if f["type"] == "intron"]

    trna_genes = [f for f in trna_f if f["type"] in ("gene", "tRNA")]

    # Functional annotations
    func_rows = []
    with open(args.functional_tsv) as fh:
        reader = csv.DictReader(fh, delimiter="\t")
        for row in reader:
            func_rows.append(row)

    # Gene summary
    gene_summary = []
    with open(args.gene_summary) as fh:
        reader = csv.DictReader(fh, delimiter="\t")
        for row in reader:
            gene_summary.append(row)

    n_hypo = sum(1 for g in gene_summary if g.get("product") == "hypothetical protein")
    n_named = len(gene_summary) - n_hypo

    # BUSCO
    busco_text = read_file_text(args.busco_txt)

    # OMArk
    omark_summary_text = read_file_text(args.omark_summary)
    omark_detailed_text = read_file_text(args.omark_detailed)

    # AGAT stats
    agat_text = read_file_text(args.agat_stats)

    # Repeat table
    repeat_tbl_text = read_file_text(args.repeat_tbl)
    repeat_tbl_full_text = read_file_text(args.repeat_tbl_full)

    # Assembly stats
    assembly_stats_text = read_file_text(args.assembly_stats)

    # ── Compute statistics ────────────────────────────────────────────────

    # Exon counts per mRNA
    exons_per_mrna = Counter()
    for e in exons:
        parent = e["attributes"].get("Parent", "")
        exons_per_mrna[parent] += 1
    exon_counts = list(exons_per_mrna.values()) if exons_per_mrna else [0]
    median_exons = sorted(exon_counts)[len(exon_counts) // 2] if exon_counts else 0
    single_exon = sum(1 for c in exon_counts if c == 1)

    # Gene lengths
    gene_lengths = [g["length"] for g in genes]
    median_gene_len = sorted(gene_lengths)[len(gene_lengths) // 2] if gene_lengths else 0

    # Exon lengths
    exon_lengths = [e["length"] for e in exons]
    median_exon_len = sorted(exon_lengths)[len(exon_lengths) // 2] if exon_lengths else 0

    # Intron lengths
    intron_lengths = [i["length"] for i in introns]
    median_intron_len = sorted(intron_lengths)[len(intron_lengths) // 2] if intron_lengths else 0
    short_introns = sum(1 for l in intron_lengths if l < 10)

    # CDS total per mRNA
    cds_per_mrna = defaultdict(int)
    for c in cdss:
        parent = c["attributes"].get("Parent", "")
        cds_per_mrna[parent] += c["length"]
    cds_totals = list(cds_per_mrna.values()) if cds_per_mrna else [0]
    median_cds = sorted(cds_totals)[len(cds_totals) // 2] if cds_totals else 0

    # Functional coverage
    n_func = len(func_rows)
    n_ipr = sum(1 for r in func_rows if r.get("ipr_signatures", "-") != "-")
    n_egg = sum(1 for r in func_rows if r.get("eggnog_OGs", "-") != "-")
    n_dia = sum(1 for r in func_rows if r.get("diamond_hit", "-") != "-")
    n_kof = sum(1 for r in func_rows if r.get("kofam_KO", "-") != "-")
    n_sig = sum(1 for r in func_rows
                if r.get("deepsig_type", "-") not in ("-", "Other", ""))

    # Tool depth
    def tool_hits(row):
        return (
            (row.get("ipr_signatures", "-") != "-") +
            (row.get("eggnog_OGs", "-") != "-") +
            (row.get("diamond_hit", "-") != "-") +
            (row.get("kofam_KO", "-") != "-") +
            (row.get("deepsig_type", "-") not in ("-", "Other", ""))
        )
    depth_counts = Counter(tool_hits(r) for r in func_rows)

    # ncRNA families
    rfam_families = Counter()
    for f in ncrna_f:
        name = f["attributes"].get("Name", "unknown")
        rfam_families[name] += 1

    # Telomere positions
    telo_positions = Counter()
    for f in telo_f:
        pos = f["attributes"].get("position", "unknown")
        telo_positions[pos] += 1

    # Scaffolds with genes
    scaffolds_with_genes = len(set(g["seqid"] for g in genes))

    # ═════════════════════════════════════════════════════════════════════
    # Build Markdown
    # ═════════════════════════════════════════════════════════════════════
    md = []
    md.append(f"# Genome Annotation Report: `{asm}`\n")
    md.append(f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')}\n")
    md.append("---\n")

    # ── Table of contents ─────────────────────────────────────────────
    md.append("## Table of Contents\n")
    md.append("""
1. [Assembly Summary](#1-assembly-summary)
2. [Annotation Overview](#2-annotation-overview)
3. [Gene Model Structure](#3-gene-model-structure)
4. [Repeat Annotation](#4-repeat-annotation)
5. [Non-coding RNA](#5-non-coding-rna)
6. [Telomeres & Centromeres](#6-telomeres--centromeres)
7. [Quality Assessment](#7-quality-assessment)
8. [Functional Annotation](#8-functional-annotation)
9. [GO & Pathway Analysis](#9-go--pathway-analysis)
10. [Tuning Recommendations](#10-tuning-recommendations)
""")

    # ═════════════════════════════════════════════════════════════════════
    # Section 1: Assembly Summary
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 1. Assembly Summary\n")
    md.append("```\n" + assembly_stats_text.strip() + "\n```\n")

    # ═════════════════════════════════════════════════════════════════════
    # Section 2: Annotation Overview
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 2. Annotation Overview\n")
    md.append(f"""
| Feature type | Count |
|:---|---:|
| Protein-coding genes | {fmt(len(genes))} |
| mRNA transcripts | {fmt(len(mrnas))} |
| Exons | {fmt(len(exons))} |
| CDS features | {fmt(len(cdss))} |
| Introns | {fmt(len(introns))} |
| tRNA genes | {fmt(len(trna_genes))} |
| ncRNA features (Rfam) | {fmt(len(ncrna_f))} |
| Telomeric regions | {fmt(len(telo_f))} |
| Centromere features | {fmt(len(centro_f))} |
| Repeat features | {fmt(len(repeat_f))} |
| Scaffolds with genes | {fmt(scaffolds_with_genes)} |
""")

    # ═════════════════════════════════════════════════════════════════════
    # Section 3: Gene Model Structure
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 3. Gene Model Structure\n")
    md.append(f"""
| Metric | Value |
|:---|---:|
| Median gene length | {fmt(median_gene_len)} bp |
| Median exon length | {fmt(median_exon_len)} bp |
| Median intron length | {fmt(median_intron_len)} bp |
| Median total CDS per transcript | {fmt(median_cds)} bp |
| Median exons per transcript | {median_exons} |
| Single-exon transcripts | {fmt(single_exon)} ({pct(single_exon, len(exon_counts))}) |
| Introns < 10 bp (suspicious) | {fmt(short_introns)} |
""")

    md.append("### Gene length distribution\n")
    md.append(img(pd, "A1_gene_length_distribution.png"))

    md.append("### Exons per transcript\n")
    md.append(img(pd, "A1_exons_per_transcript.png"))

    md.append("### Exon length distribution\n")
    md.append(img(pd, "A1_exon_length_distribution.png"))

    md.append("### Intron length distribution\n")
    md.append(img(pd, "A1_intron_length_distribution.png"))

    md.append("### CDS length per transcript\n")
    md.append(img(pd, "A1_cds_length_distribution.png"))

    md.append("### Gene length vs exon count\n")
    md.append(img(pd, "B3_gene_length_vs_exons.png"))

    md.append("### Genes per scaffold (top 30)\n")
    md.append(img(pd, "A10_genes_per_scaffold.png"))

    # ═════════════════════════════════════════════════════════════════════
    # Section 4: Repeat Annotation
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 4. Repeat Annotation\n")
    md.append("### RepeatMasker summary\n")
    md.append("```\n" + repeat_tbl_text.strip() + "\n```\n")

    md.append("### Repeat composition by class\n")
    md.append(img(pd, "B5_repeat_composition.png"))

    md.append("### Detailed repeat family summary (buildSummary.pl)\n")
    md.append("<details>\n<summary>Click to expand</summary>\n\n")
    md.append("```\n" + repeat_tbl_full_text.strip() + "\n```\n")
    md.append("</details>\n")

    md.append("""
> **Note:** The repeat landscape HTML (`repeat_landscape.html`) is available
> in the `repeats/` output directory and can be viewed in a browser for an
> interactive divergence-based view of repeat accumulation history.
""")

    # ═════════════════════════════════════════════════════════════════════
    # Section 5: Non-coding RNA
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 5. Non-coding RNA\n")

    md.append(f"""
| Feature | Count |
|:---|---:|
| tRNA genes | {fmt(len(trna_genes))} |
| ncRNA features (Infernal/Rfam) | {fmt(len(ncrna_f))} |
| Unique Rfam families | {fmt(len(rfam_families))} |
""")

    md.append("### tRNA isotype distribution\n")
    md.append(img(pd, "A7_trna_isotypes.png"))

    md.append("### ncRNA Rfam families (top 25)\n")
    md.append(img(pd, "A8_ncrna_rfam_families.png"))

    # Top Rfam families table
    if rfam_families:
        md.append("\n| Rfam family | Count |\n|:---|---:|\n")
        for fam, cnt in rfam_families.most_common(15):
            md.append(f"| {fam} | {fmt(cnt)} |\n")
        md.append("\n")

    # ═════════════════════════════════════════════════════════════════════
    # Section 6: Telomeres & Centromeres
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 6. Telomeres & Centromeres\n")

    md.append("### Telomere annotation\n")
    md.append(f"Total telomeric regions: **{len(telo_f)}**\n\n")
    if telo_positions:
        md.append("| Position class | Count |\n|:---|---:|\n")
        for pos, cnt in telo_positions.most_common():
            md.append(f"| {pos} | {cnt} |\n")
        md.append("\n")
    md.append(img(pd, "A9_telomere_positions.png"))

    md.append("""
> **Note:** The tidk telomere density SVG plot is available in the
> `telomeres/` output directory for a per-scaffold visual.
""")

    md.append("### Centromere annotation\n")
    md.append(f"Total centromere features (centroAnno): **{len(centro_f)}**\n\n")
    if centro_f:
        scaffolds_with_centro = len(set(f["seqid"] for f in centro_f))
        md.append(f"Scaffolds with centromere annotations: **{scaffolds_with_centro}**\n\n")

        # Type breakdown
        centro_types = Counter(f["type"] for f in centro_f)
        md.append("| Feature type | Count |\n|:---|---:|\n")
        for t, c in centro_types.most_common():
            md.append(f"| {t} | {fmt(c)} |\n")
        md.append("\n")

    # ═════════════════════════════════════════════════════════════════════
    # Section 7: Quality Assessment
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 7. Quality Assessment\n")

    md.append("### BUSCO completeness\n")
    md.append("```\n" + busco_text.strip() + "\n```\n")
    md.append(img(pd, "B1_busco_completeness.png"))

    md.append("### OMArk assessment\n")
    md.append("```\n" + omark_summary_text.strip() + "\n```\n")

    md.append("<details>\n<summary>OMArk detailed output</summary>\n\n")
    md.append("```\n" + omark_detailed_text.strip() + "\n```\n")
    md.append("</details>\n")

    md.append("### AGAT structural statistics\n")
    md.append("<details>\n<summary>Click to expand full AGAT output</summary>\n\n")
    md.append("```\n" + agat_text.strip() + "\n```\n")
    md.append("</details>\n")

    md.append("### Intron length QC\n")
    md.append(img(pd, "B2_intron_length_qc.png"))

    # ═════════════════════════════════════════════════════════════════════
    # Section 8: Functional Annotation
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 8. Functional Annotation\n")

    md.append(f"""
| Tool | Proteins annotated | Coverage |
|:---|---:|---:|
| InterProScan | {fmt(n_ipr)} | {pct(n_ipr, n_func)} |
| eggNOG-mapper | {fmt(n_egg)} | {pct(n_egg, n_func)} |
| DIAMOND (SwissProt) | {fmt(n_dia)} | {pct(n_dia, n_func)} |
| KofamScan | {fmt(n_kof)} | {pct(n_kof, n_func)} |
| DeepSig (signal peptides) | {fmt(n_sig)} | {pct(n_sig, n_func)} |
| **Total proteins** | **{fmt(n_func)}** | |

**Product names:** {fmt(n_named)} named ({pct(n_named, len(gene_summary))}), \
{fmt(n_hypo)} hypothetical ({pct(n_hypo, len(gene_summary))})
""")

    md.append("### Tool coverage\n")
    md.append(img(pd, "A2_functional_coverage.png"))

    md.append("### Annotation depth per protein\n")
    md.append(img(pd, "A2_annotation_depth.png"))

    md.append("| Tools with hits | Proteins | % |\n|:---|---:|---:|\n")
    for depth in sorted(depth_counts.keys()):
        cnt = depth_counts[depth]
        md.append(f"| {depth} | {fmt(cnt)} | {pct(cnt, n_func)} |\n")
    md.append("\n")

    md.append("### Tool overlap matrix\n")
    md.append(img(pd, "B4_tool_overlap_matrix.png"))

    md.append("### Product name composition\n")
    md.append(img(pd, "A3_product_composition.png"))

    md.append("### Top 20 gene products\n")
    md.append(img(pd, "A3_top_products.png"))

    md.append("### Top InterPro domains\n")
    md.append(img(pd, "A6_top_interpro_domains.png"))

    # ═════════════════════════════════════════════════════════════════════
    # Section 9: GO & Pathway Analysis
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 9. GO & Pathway Analysis\n")

    # GO stats
    all_go = set()
    for r in func_rows:
        for field in ("ipr_go", "eggnog_GO"):
            raw = r.get(field, "-")
            if raw and raw != "-":
                for t in re.split(r"[;,|]+", raw):
                    t = t.strip()
                    if t.startswith("GO:"):
                        all_go.add(t)

    # KEGG stats
    all_kegg_ko = set()
    for r in func_rows:
        for field in ("eggnog_KEGG_ko", "kofam_KO"):
            raw = r.get(field, "-")
            if raw and raw != "-":
                for t in re.split(r"[;,]+", raw):
                    t = t.strip()
                    if t:
                        all_kegg_ko.add(t)

    all_kegg_path = set()
    for r in func_rows:
        raw = r.get("eggnog_KEGG_path", "-")
        if raw and raw != "-":
            for t in re.split(r"[;,]+", raw):
                t = t.strip()
                if t:
                    all_kegg_path.add(t)

    md.append(f"""
| Metric | Value |
|:---|---:|
| Unique GO terms | {fmt(len(all_go))} |
| Unique KEGG KOs | {fmt(len(all_kegg_ko))} |
| Unique KEGG pathways | {fmt(len(all_kegg_path))} |
""")

    md.append("### Top GO terms\n")
    md.append(img(pd, "A4_top_go_terms.png"))

    md.append("### Top KEGG terms\n")
    md.append(img(pd, "A5_top_kegg_terms.png"))

    md.append("""
> **For cross-assembly comparison:** run this report on each assembly
> and compare the GO/KEGG/IPR counts and coverage percentages side by side.
> Key comparative metrics:
> - BUSCO completeness %
> - Named product % (higher = better functional characterization)
> - Annotation depth distribution (shift toward more tools = better)
> - Unique GO terms (proxy for functional diversity captured)
> - Hypothetical protein % (lower = better)
""")

    # ═════════════════════════════════════════════════════════════════════
    # Section 10: Tuning Recommendations
    # ═════════════════════════════════════════════════════════════════════
    md.append("---\n## 10. Tuning Recommendations\n")
    md.append("""
This section flags potential issues and suggests parameter adjustments
based on the statistics above.

""")

    flags = []

    # Flag: high hypothetical protein rate
    if len(gene_summary) > 0 and n_hypo / len(gene_summary) > 0.5:
        flags.append(
            f"- **High hypothetical protein rate ({pct(n_hypo, len(gene_summary))}):** "
            "Consider adding RNA-seq evidence to BRAKER3 (`--rnaseq_bam`), "
            "expanding the OrthoDB protein set to more lineages, or running "
            "additional functional tools."
        )

    # Flag: many single-exon genes
    if len(exon_counts) > 0 and single_exon / len(exon_counts) > 0.3:
        flags.append(
            f"- **High single-exon gene rate ({pct(single_exon, len(exon_counts))}):** "
            "This may indicate under-predicted gene structures. RNA-seq "
            "evidence can improve exon-intron boundary detection."
        )

    # Flag: suspicious short introns
    if short_introns > 50:
        flags.append(
            f"- **{fmt(short_introns)} introns < 10 bp:** "
            "These are likely gene model artifacts. Consider post-filtering "
            "with AGAT or TSEBRA to clean up micro-introns."
        )

    # Flag: low BUSCO
    busco_complete = 0.0
    bs_match = re.search(r"C:([0-9.]+)%", busco_text)
    if bs_match:
        busco_complete = float(bs_match.group(1))
    if busco_complete < 80:
        flags.append(
            f"- **Low BUSCO completeness ({busco_complete:.1f}%):** "
            "Check repeat masking quality, assembly contiguity, or try "
            "increasing BRAKER3 `--rounds`. Missing BUSCOs may also "
            "indicate assembly gaps."
        )

    # Flag: low functional coverage
    if n_func > 0 and n_dia / n_func < 0.3:
        flags.append(
            f"- **Low DIAMOND/SwissProt coverage ({pct(n_dia, n_func)}):** "
            "Consider supplementing with TrEMBL or NR database for broader "
            "homology detection. This mainly affects product name assignment."
        )

    # Flag: repeat masking percentage
    mask_match = re.search(r"bases masked:.*?\(\s*([\d.]+)\s*%\s*\)", repeat_tbl_text)
    if mask_match:
        mask_pct = float(mask_match.group(1))
        if mask_pct < 20:
            flags.append(
                f"- **Low repeat masking ({mask_pct:.1f}%):** "
                "Fish genomes typically have 30-50% repetitive content. "
                "Consider adding more RepeatModeler rounds "
                "(`--repModel_rounds`), using a more sensitive RM speed "
                "(`-s` instead of `-q`), or expanding Dfam taxon scope."
            )

    if not flags:
        flags.append("- No major issues detected. Annotation parameters appear well-tuned.")

    for f in flags:
        md.append(f + "\n")

